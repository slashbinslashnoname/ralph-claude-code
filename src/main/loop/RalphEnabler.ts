/**
 * RalphEnabler.ts — TypeScript replacement for ralph_enable.sh.
 *
 * Detects project context, generates all Ralph template files, and
 * validates an existing Ralph setup. No shell scripts involved.
 */

import {
  existsSync, mkdirSync, writeFileSync, readFileSync, readdirSync
} from 'fs'
import { join, basename } from 'path'

// ── Project detection ────────────────────────────────────────────────────────

export type ProjectType =
  | 'nodejs' | 'python' | 'rust' | 'go' | 'java' | 'ruby' | 'php' | 'unknown'

export interface ProjectContext {
  type: ProjectType
  name: string
  hasGit: boolean
  hasBeads: boolean
  installCmd: string
  testCmd: string
  buildCmd: string
}

const TYPE_MARKERS: [ProjectType, string, string, string, string][] = [
  // [type, marker file, install, test, build]
  ['nodejs',  'package.json',     'npm install',    'npm test',          'npm run build'],
  ['python',  'pyproject.toml',   'pip install -e .', 'pytest',          'python -m build'],
  ['python',  'setup.py',         'pip install -e .', 'pytest',          'python setup.py build'],
  ['python',  'requirements.txt', 'pip install -r requirements.txt', 'pytest', ''],
  ['rust',    'Cargo.toml',       'cargo build',    'cargo test',        'cargo build --release'],
  ['go',      'go.mod',           'go mod download', 'go test ./...',    'go build ./...'],
  ['java',    'pom.xml',          'mvn install',    'mvn test',          'mvn package'],
  ['java',    'build.gradle',     'gradle build',   'gradle test',       'gradle jar'],
  ['ruby',    'Gemfile',          'bundle install', 'bundle exec rspec', ''],
  ['php',     'composer.json',    'composer install', 'vendor/bin/phpunit', '']
]

export function detectProjectContext(projectPath: string): ProjectContext {
  let type: ProjectType = 'unknown'
  let installCmd = ''
  let testCmd = ''
  let buildCmd = ''

  for (const [t, marker, install, test, build] of TYPE_MARKERS) {
    if (existsSync(join(projectPath, marker))) {
      type = t; installCmd = install; testCmd = test; buildCmd = build
      break
    }
  }

  // Refine Node.js name from package.json
  let name = basename(projectPath)
  if (type === 'nodejs') {
    try {
      const pkg = JSON.parse(readFileSync(join(projectPath, 'package.json'), 'utf8')) as { name?: string }
      if (pkg.name) name = pkg.name
    } catch { /* keep basename */ }
  }

  return {
    type,
    name,
    hasGit:   existsSync(join(projectPath, '.git')),
    hasBeads: existsSync(join(projectPath, '.beads')),
    installCmd,
    testCmd,
    buildCmd
  }
}

// ── Enabled check ────────────────────────────────────────────────────────────

export interface EnabledStatus {
  enabled: boolean
  missing: string[]
  hasRalphrc: boolean
  hasRalphDir: boolean
}

const REQUIRED = ['.ralphrc', '.ralph', '.ralph/PROMPT.md', '.ralph/fix_plan.md', '.ralph/AGENT.md']

export function checkEnabled(projectPath: string): EnabledStatus {
  const missing = REQUIRED.filter(p => !existsSync(join(projectPath, p)))
  return {
    enabled:    missing.length === 0,
    missing,
    hasRalphrc: existsSync(join(projectPath, '.ralphrc')),
    hasRalphDir: existsSync(join(projectPath, '.ralph'))
  }
}

// ── Template generators ──────────────────────────────────────────────────────

function generateRalphrc(ctx: ProjectContext, opts: EnableOptions): string {
  const tools = [
    'Write', 'Read', 'Edit',
    'Bash(git add *)', 'Bash(git commit *)', 'Bash(git status)',
    'Bash(git diff)', 'Bash(git log)',
    ...(ctx.type === 'nodejs'  ? ['Bash(npm *)']        : []),
    ...(ctx.type === 'python'  ? ['Bash(pytest)', 'Bash(pip *)'] : []),
    ...(ctx.type === 'rust'    ? ['Bash(cargo *)']      : []),
    ...(ctx.type === 'go'      ? ['Bash(go *)']         : []),
    ...(ctx.type === 'java'    ? ['Bash(mvn *)', 'Bash(gradle *)'] : []),
    ...(ctx.type === 'ruby'    ? ['Bash(bundle *)', 'Bash(rspec)'] : [])
  ].join(',')

  return [
    `# Ralph configuration — generated by Ralph Desktop`,
    `# Project: ${ctx.name} (${ctx.type})`,
    ``,
    `# API / rate limiting`,
    `MAX_CALLS_PER_HOUR=${opts.maxCallsPerHour}`,
    `CLAUDE_TIMEOUT_MINUTES=15`,
    ``,
    `# Output and model`,
    `CLAUDE_OUTPUT_FORMAT=json`,
    `CLAUDE_CODE_CMD=claude`,
    ``,
    `# Tool permissions`,
    `CLAUDE_ALLOWED_TOOLS="${tools}"`,
    ``,
    `# Loop timing`,
    `SLEEP_DURATION=3`,
    ``,
    `# Circuit breaker`,
    `CB_NO_PROGRESS_THRESHOLD=3`,
    `CB_SAME_ERROR_THRESHOLD=5`,
    `CB_PERMISSION_DENIAL_THRESHOLD=2`,
    `CB_COOLDOWN_MINUTES=30`,
    ``,
    `# Task sources: local, beads`,
    `TASK_SOURCES="${opts.useBeads ? 'beads' : 'local'}"`,
    ``
  ].join('\n')
}

function generatePromptMd(ctx: ProjectContext, opts: EnableOptions): string {
  return `# Ralph Development Instructions

You are an autonomous developer working on **${ctx.name}** (${ctx.type} project).

## Your task

Work through the items in \`.ralph/fix_plan.md\` one by one, implementing each task completely before moving to the next.

## Guidelines

- Read \`.ralph/fix_plan.md\` at the start of each iteration to see remaining tasks
- Implement ONE task at a time — don't skip ahead
- After implementing a task, run tests: \`${ctx.testCmd || 'your test command'}\`
- Commit your work: \`git add -A && git commit -m "feat: description"\`
- Mark the task done in fix_plan.md: change \`- [ ]\` to \`- [x]\`
- If a task is unclear, make a reasonable assumption and document it in a comment

## Protected files (DO NOT modify or delete)

- \`.ralph/\` directory and all its contents
- \`.ralphrc\`

## Build commands

\`\`\`bash
# Install:  ${ctx.installCmd || 'your install command'}
# Test:     ${ctx.testCmd    || 'your test command'}
# Build:    ${ctx.buildCmd   || 'your build command'}
\`\`\`

## Status reporting

End every response with a RALPH_STATUS block so the loop engine can track progress:

\`\`\`
RALPH_STATUS: {
  "STATUS": "IN_PROGRESS",
  "EXIT_SIGNAL": false,
  "WORK_TYPE": "feature",
  "FILES_MODIFIED": 0,
  "ASKING_QUESTIONS": false,
  "QUESTION_COUNT": 0,
  "WORK_SUMMARY": "brief description of what was done"
}
\`\`\`

Set \`EXIT_SIGNAL\` to \`true\` only when ALL tasks in fix_plan.md are complete (\`- [x]\`).
`
}

function generateFixPlanMd(opts: EnableOptions): string {
  const tasks = opts.initialTasks.length > 0
    ? opts.initialTasks.map(t => `- [ ] ${t}`).join('\n')
    : [
        '- [ ] Review the codebase and understand the project structure',
        '- [ ] Add your tasks here',
        '- [ ] Each task on its own line — Ralph will work through them in order'
      ].join('\n')

  return `# Tasks\n\n${tasks}\n`
}

function generateAgentMd(ctx: ProjectContext): string {
  const sections: string[] = [`# Build & Run — ${ctx.name}`]

  if (ctx.installCmd) {
    sections.push(`\n## Install dependencies\n\`\`\`bash\n${ctx.installCmd}\n\`\`\``)
  }
  if (ctx.testCmd) {
    sections.push(`\n## Run tests\n\`\`\`bash\n${ctx.testCmd}\n\`\`\``)
  }
  if (ctx.buildCmd) {
    sections.push(`\n## Build\n\`\`\`bash\n${ctx.buildCmd}\n\`\`\``)
  }

  sections.push(`\n## Notes\n\n_Update this file as the project evolves._\n`)
  return sections.join('\n')
}

function generateGitignoreAdditions(): string {
  return [
    '',
    '# Ralph',
    '.ralph/logs/',
    '.ralph/.call_count',
    '.ralph/.exit_signals',
    '.ralph/.response_analysis',
    '.ralph/.circuit_breaker_state',
    '.ralph/.circuit_breaker_history',
    '.ralph/.claude_session_id',
    '.ralph/.ralph_session_history',
    '.ralph/progress.json',
    ''
  ].join('\n')
}

// ── Enable options ───────────────────────────────────────────────────────────

export interface EnableOptions {
  force: boolean
  maxCallsPerHour: number
  useBeads: boolean
  initialTasks: string[]
}

export const DEFAULT_ENABLE_OPTIONS: EnableOptions = {
  force: false,
  maxCallsPerHour: 100,
  useBeads: false,
  initialTasks: []
}

// ── Main enable function ─────────────────────────────────────────────────────

export interface EnableResult {
  ok: boolean
  error?: string
  filesCreated: string[]
  alreadyEnabled: boolean
  context: ProjectContext
}

export function enableRalph(projectPath: string, opts: EnableOptions = DEFAULT_ENABLE_OPTIONS): EnableResult {
  const status = checkEnabled(projectPath)
  if (status.enabled && !opts.force) {
    return {
      ok: true, alreadyEnabled: true, filesCreated: [],
      context: detectProjectContext(projectPath)
    }
  }

  const ctx = detectProjectContext(projectPath)
  const created: string[] = []

  try {
    // 1. Create .ralph/ directory
    const ralphDir = join(projectPath, '.ralph')
    mkdirSync(ralphDir, { recursive: true })
    mkdirSync(join(ralphDir, 'logs'), { recursive: true })

    const write = (relPath: string, content: string): void => {
      const full = join(projectPath, relPath)
      if (!existsSync(full) || opts.force) {
        writeFileSync(full, content, 'utf8')
        created.push(relPath)
      }
    }

    // 2. Generate template files
    write('.ralphrc',           generateRalphrc(ctx, opts))
    write('.ralph/PROMPT.md',   generatePromptMd(ctx, opts))
    write('.ralph/fix_plan.md', generateFixPlanMd(opts))
    write('.ralph/AGENT.md',    generateAgentMd(ctx))

    // 3. Update .gitignore (append Ralph section if not already present)
    const gitignorePath = join(projectPath, '.gitignore')
    const existing = existsSync(gitignorePath) ? readFileSync(gitignorePath, 'utf8') : ''
    if (!existing.includes('# Ralph')) {
      writeFileSync(gitignorePath, existing + generateGitignoreAdditions())
    }

    return { ok: true, alreadyEnabled: false, filesCreated: created, context: ctx }
  } catch (e: unknown) {
    return {
      ok: false,
      error: e instanceof Error ? e.message : String(e),
      alreadyEnabled: false,
      filesCreated: created,
      context: ctx
    }
  }
}
