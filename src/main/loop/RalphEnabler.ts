import * as fs from 'fs'
import * as path from 'path'
import { ProjectContext, EnableOptions, EnableResult } from '../types'
import { ProjectPaths, ensureStoreDirs } from './ProjectStore'

const TYPE_MARKERS: [string, string, string, string, string][] = [
  ['nodejs', 'package.json', 'npm install', 'npm test', 'npm run build'],
  ['python', 'pyproject.toml', 'pip install -e .', 'pytest', 'python -m build'],
  ['python', 'setup.py', 'pip install -e .', 'pytest', 'python setup.py build'],
  ['python', 'requirements.txt', 'pip install -r requirements.txt', 'pytest', ''],
  ['rust', 'Cargo.toml', 'cargo build', 'cargo test', 'cargo build --release'],
  ['go', 'go.mod', 'go mod download', 'go test ./...', 'go build ./...'],
  ['java', 'pom.xml', 'mvn install', 'mvn test', 'mvn package'],
  ['java', 'build.gradle', 'gradle build', 'gradle test', 'gradle jar'],
  ['ruby', 'Gemfile', 'bundle install', 'bundle exec rspec', ''],
  ['php', 'composer.json', 'composer install', 'vendor/bin/phpunit', '']
]

export function detectProjectContext(projectPath: string, beadsRoot?: string): ProjectContext {
  let type = 'unknown', installCmd = '', testCmd = '', buildCmd = ''
  for (const [t, marker, install, test, build] of TYPE_MARKERS) {
    if (fs.existsSync(path.join(projectPath, marker))) {
      type = t; installCmd = install; testCmd = test; buildCmd = build; break
    }
  }
  let name = path.basename(projectPath)
  if (type === 'nodejs') {
    try {
      const pkg = JSON.parse(fs.readFileSync(path.join(projectPath, 'package.json'), 'utf8'))
      if (pkg.name) name = pkg.name
    } catch { /* ignore */ }
  }
  const hasBeads = beadsRoot
    ? fs.existsSync(beadsRoot)
    : fs.existsSync(path.join(projectPath, '.beads'))
  return {
    type, name,
    hasGit: fs.existsSync(path.join(projectPath, '.git')),
    hasBeads,
    installCmd, testCmd, buildCmd
  }
}

const REQUIRED_LEGACY = ['.slashbotrc', '.slashbot', '.slashbot/PROMPT.md', '.slashbot/AGENT.md']

export function checkEnabled(projectPath: string, paths?: ProjectPaths): {
  enabled: boolean; missing: string[]; hasRalphrc: boolean; hasRalphDir: boolean
} {
  if (paths) {
    const configDir = paths.configDir
    const required: [string, string][] = [
      ['.slashbotrc', path.join(configDir, '.slashbotrc')],
      ['PROMPT.md', path.join(configDir, 'PROMPT.md')],
      ['AGENT.md', path.join(configDir, 'AGENT.md')],
    ]
    const missing = required.filter(([, abs]) => !fs.existsSync(abs)).map(([name]) => name)
    return {
      enabled: missing.length === 0,
      missing,
      hasRalphrc: fs.existsSync(path.join(configDir, '.slashbotrc')),
      hasRalphDir: fs.existsSync(configDir)
    }
  }
  const missing = REQUIRED_LEGACY.filter(p => !fs.existsSync(path.join(projectPath, p)))
  return {
    enabled: missing.length === 0,
    missing,
    hasRalphrc: fs.existsSync(path.join(projectPath, '.slashbotrc')),
    hasRalphDir: fs.existsSync(path.join(projectPath, '.slashbot'))
  }
}

function generateRalphrc(ctx: ProjectContext, opts: EnableOptions): string {
  const tools = [
    'Write', 'Read', 'Edit',
    'Bash(git add *)', 'Bash(git commit *)', 'Bash(git status)', 'Bash(git diff)', 'Bash(git log)',
    'Bash(bd *)',
    ...(ctx.type === 'nodejs' ? ['Bash(npm *)'] : []),
    ...(ctx.type === 'python' ? ['Bash(pytest)', 'Bash(pip *)'] : []),
    ...(ctx.type === 'rust' ? ['Bash(cargo *)'] : []),
    ...(ctx.type === 'go' ? ['Bash(go *)'] : []),
  ].join(',')
  return [
    '# Slashbot configuration \u2014 generated by Slashbot',
    `# Project: ${ctx.name} (${ctx.type})`, '',
    `MAX_CALLS_PER_HOUR=${opts.maxCallsPerHour}`,
    'CLAUDE_TIMEOUT_MINUTES=15', '',
    'CLAUDE_OUTPUT_FORMAT=json',
    'CLAUDE_CODE_CMD=claude', '',
    `CLAUDE_ALLOWED_TOOLS="${tools}"`, '',
    'SLEEP_DURATION=3', '',
    'CB_NO_PROGRESS_THRESHOLD=3',
    'CB_SAME_ERROR_THRESHOLD=5',
    'CB_PERMISSION_DENIAL_THRESHOLD=2',
    'CB_COOLDOWN_MINUTES=30', '',
    `TASK_SOURCES="${opts.useBeads ? 'beads' : 'local'}"`, '',
    '# Model routing — choose which Claude model to use for each phase',
    '# CLAUDE_MODEL_THINK=sonnet',
    '# CLAUDE_MODEL_EXECUTE=opus',
    '# CLAUDE_MODEL_REVIEW=sonnet', ''
  ].join('\n')
}

function generatePromptMd(ctx: ProjectContext, centralized = false): string {
  const protectedFiles = centralized
    ? '- `.slashbotid`'
    : '- `.slashbot/` directory and all its contents\n- `.slashbotrc`'
  return `# Slashbot Development Instructions

You are an autonomous developer working on **${ctx.name}** (${ctx.type} project).

## Your task
Work through assigned beads one by one, implementing each completely before moving to the next.

## Beads (bd CLI)
Use \`bd\` to manage your work items:
\`\`\`bash
bd ready --json        # Find unblocked work
bd update <id> --claim # Claim a bead
bd close <id> --reason "Done" # Close when finished
bd create "title" -t task -p 2 -d "desc" # Create if you discover new work
\`\`\`

## Guidelines
- Implement ONE bead at a time
- After implementing, run tests: \`${ctx.testCmd || 'your test command'}\`
- Commit your work: \`git add -A && git commit -m "feat: description"\`
- Close the bead via bd when done

## Protected files (DO NOT modify or delete)
${protectedFiles}

## Status reporting
End every response with:
\`\`\`
RALPH_STATUS: { "STATUS": "IN_PROGRESS", "EXIT_SIGNAL": false, "WORK_TYPE": "feature", "FILES_MODIFIED": 0, "ASKING_QUESTIONS": false, "QUESTION_COUNT": 0, "WORK_SUMMARY": "brief description" }
\`\`\`
Set \`EXIT_SIGNAL\` to \`true\` only when ALL assigned beads are complete.
`
}

function generateAgentMd(ctx: ProjectContext): string {
  const sections = [`# Build & Run \u2014 ${ctx.name}`]
  if (ctx.installCmd) sections.push(`\n## Install\n\`\`\`bash\n${ctx.installCmd}\n\`\`\``)
  if (ctx.testCmd) sections.push(`\n## Test\n\`\`\`bash\n${ctx.testCmd}\n\`\`\``)
  if (ctx.buildCmd) sections.push(`\n## Build\n\`\`\`bash\n${ctx.buildCmd}\n\`\`\``)
  sections.push('\n## Notes\n\n_Update this file as the project evolves._\n')
  return sections.join('\n')
}

function generateGitignoreAdditions(centralized = false): string {
  if (centralized) {
    return '\n# Slashbot\n.slashbotid\n'
  }
  return '\n# Slashbot\n.slashbot/logs/\n.slashbot/.call_count\n.slashbot/.exit_signals\n.slashbot/.response_analysis\n.slashbot/.circuit_breaker_state\n.slashbot/.claude_session_id\n.slashbot/progress.json\n'
}

const DEFAULT_ENABLE_OPTIONS: EnableOptions = {
  force: false, maxCallsPerHour: 100, useBeads: false, initialTasks: []
}

export function enableRalph(projectPath: string, opts: EnableOptions = DEFAULT_ENABLE_OPTIONS, paths?: ProjectPaths): EnableResult {
  const status = checkEnabled(projectPath, paths)
  if (status.enabled && !opts.force) {
    return { ok: true, alreadyEnabled: true, filesCreated: [], context: detectProjectContext(projectPath) }
  }
  const ctx = detectProjectContext(projectPath)
  const created: string[] = []
  try {
    if (paths) {
      ensureStoreDirs(paths)
      const configDir = paths.configDir
      const write = (name: string, content: string) => {
        const full = path.join(configDir, name)
        if (!fs.existsSync(full) || opts.force) {
          fs.writeFileSync(full, content, 'utf8')
          created.push(name)
        }
      }
      write('.slashbotrc', generateRalphrc(ctx, opts))
      write('PROMPT.md', generatePromptMd(ctx, true))
      write('AGENT.md', generateAgentMd(ctx))
      // Write .slashbotid pointer in project root
      const idPath = path.join(projectPath, '.slashbotid')
      if (!fs.existsSync(idPath) || opts.force) {
        fs.writeFileSync(idPath, paths.id + '\n', 'utf8')
        created.push('.slashbotid')
      }
    } else {
      const slashbotDir = path.join(projectPath, '.slashbot')
      fs.mkdirSync(slashbotDir, { recursive: true })
      fs.mkdirSync(path.join(slashbotDir, 'logs'), { recursive: true })
      const write = (relPath: string, content: string) => {
        const full = path.join(projectPath, relPath)
        if (!fs.existsSync(full) || opts.force) {
          fs.writeFileSync(full, content, 'utf8')
          created.push(relPath)
        }
      }
      write('.slashbotrc', generateRalphrc(ctx, opts))
      write('.slashbot/PROMPT.md', generatePromptMd(ctx))
      write('.slashbot/AGENT.md', generateAgentMd(ctx))
    }
    const gitignorePath = path.join(projectPath, '.gitignore')
    const existing = fs.existsSync(gitignorePath) ? fs.readFileSync(gitignorePath, 'utf8') : ''
    if (!existing.includes('# Slashbot')) {
      fs.writeFileSync(gitignorePath, existing + generateGitignoreAdditions(!!paths))
    }
    return { ok: true, alreadyEnabled: false, filesCreated: created, context: ctx }
  } catch (e) {
    return { ok: false, error: e instanceof Error ? e.message : String(e), alreadyEnabled: false, filesCreated: created, context: ctx }
  }
}
